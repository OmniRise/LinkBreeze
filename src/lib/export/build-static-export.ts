function adjustmentStyleString(adj: {
  fit?: string | null;
  posX?: number | null;
  posY?: number | null;
  zoom?: number | null;
}): string {
  const s = imageAdjustmentStyle(adj);
  let out = `object-fit:${s.objectFit};object-position:${s.objectPosition}`;
  if (s.transform && s.transformOrigin) {
    out += `;transform:${s.transform};transform-origin:${s.transformOrigin}`;
  }
  return out;
}

/** Avatar border styles per avatarBorder token (mirrors ProfileHeader). */
function avatarBorderStyleString(border: string): string {
  const radius = "var(--lb-avatar-radius, 9999px)";
  switch (border) {
    case "none":
      return `border-radius:${radius}`;
    case "glow":
      return `border-radius:${radius};box-shadow:0 0 24px var(--lb-avatar-glow)`;
    case "gradient":
      return `border-radius:${radius};background:var(--lb-avatar-gradient)`;
    case "ring":
      return `border-radius:${radius};box-shadow:0 0 0 3px var(--lb-accent);padding:6px`;
    default:
      return `border-radius:${radius};border:2px solid var(--lb-avatar-border, var(--lb-accent))`;
  }
}

function avatarHtml(page: ExportPageInput, theme: ThemeInput): string {
  const shape = theme.avatarShape ?? "circle";
  const border = theme.avatarBorder ?? "solid";
  const float =
    theme.avatarFloat === true || theme.avatarFloat === "true" ? " lb-float" : "";
  const ringPad = border === "ring" ? 6 : 2;
  const inner = `calc(var(--lb-avatar-size, 94px) - ${ringPad * 2}px)`;
  const reveal = revealAnimation(theme.animationType, 0);
  const displayName = page.title || "";

  const innerHtml = page.avatarUrl
    ? `<img src="${esc(page.avatarUrl)}" alt="${esc(displayName)}" loading="eager" style="width:${inner};height:${inner};border-radius:var(--lb-avatar-radius, 9999px);${adjustmentStyleString({ fit: page.avatarFit, posX: page.avatarPosX, posY: page.avatarPosY, zoom: page.avatarZoom })}" />`
    : `<span style="display:flex;align-items:center;justify-content:center;width:${inner};height:${inner};font-size:calc(var(--lb-avatar-size, 94px) * 0.4);font-weight:600;background:var(--lb-card-bg);color:var(--lb-accent);border-radius:var(--lb-avatar-radius, 9999px)">${esc(
        displayName.charAt(0).toUpperCase() || "?",
      )}</span>`;

  return `<div style="${reveal}" data-avatar-shape="${esc(shape)}">
    <div class="lb-pixel-avatar${float}" style="${avatarBorderStyleString(border)};padding:${ringPad}px;width:var(--lb-avatar-size, 94px);height:var(--lb-avatar-size, 94px);display:flex;align-items:center;justify-content:center;overflow:hidden;margin:0 0 1rem">
      ${innerHtml}
    </div>
  </div>`;
}

/** Display name with the optional text animations (mirrors DisplayName). */
function displayNameHtml(name: string, theme: ThemeInput): string {
  const base =
    "color:var(--lb-text);font-family:var(--lb-font);font-weight:var(--lb-font-weight);letter-spacing:var(--lb-letter-spacing);font-size:calc(var(--lb-font-size) * 1.6);line-height:1.2;max-width:100%;word-break:break-word";
  const textAnimation = theme.textAnimation ?? "none";

  if (textAnimation === "gradient-flow") {
    return `<h1 class="lb-text-anim" style="${base};background:var(--lb-avatar-gradient);background-size:200% auto;-webkit-background-clip:text;background-clip:text;color:transparent;animation:lb-gradient-text-flow 4s linear infinite">${esc(name)}</h1>`;
  }
  if (textAnimation === "typewriter") {
    const ch = Math.max(name.length, 1);
    const typeDur = Math.max(ch * 0.08, 0.6);
    return `<h1 class="lb-text-anim lb-tw" style="${base};white-space:nowrap"><span class="lb-tw-text" style="animation:lb-tw-reveal ${typeDur}s steps(${ch}) both">${esc(name)}</span><span aria-hidden="true" class="lb-tw-caret" style="animation:lb-tw-caret-track ${typeDur}s steps(${ch}) both, lb-caret-blink 0.8s step-end infinite"></span></h1>`;
  }
  return `<h1 style="${base}">${esc(name)}</h1>`;
}

function profileHeaderHtml(page: ExportPageInput, theme: ThemeInput): string {
  const displayName = page.title || "";
  const badge = page.badgeText?.trim();
  const layout = theme.profileLayout ?? "classic";
  const banner = page.bannerUrl;

  const nameReveal = revealAnimation(theme.animationType, 80);
  const bioReveal = revealAnimation(theme.animationType, 160);
  const bio = page.bio
    ? `<p class="lb-export-bio" style="${bioReveal}">${esc(page.bio)}</p>`
    : "";
  const badgeHtml = badge
    ? `<span class="lb-pixel-border" style="display:inline-block;margin:0 0 .5rem;padding:2px 12px;font-size:.75rem;line-height:1.6;font-weight:500;color:var(--lb-text)">${esc(badge)}</span>`
    : "";

  // Hero layout: banner image with overlaid name.
  if (layout === "hero" && banner) {
    return `<header style="display:flex;flex-direction:column;color:var(--lb-text)">
      <div style="position:relative;margin:8px -1rem 1rem;overflow:hidden;border-radius:var(--lb-card-radius);max-height:240px">
        <img src="${esc(banner)}" alt="" class="lb-export-banner" style="${adjustmentStyleString({ fit: page.bannerFit, posX: page.bannerPosX, posY: page.bannerPosY, zoom: page.bannerZoom })}" />
        <div aria-hidden="true" style="position:absolute;inset:0;background:linear-gradient(to top, rgba(0,0,0,0.65), transparent 60%)"></div>
        <div style="position:absolute;bottom:0;left:0;width:100%;padding:16px;text-align:center;${nameReveal}">
          ${badge ? `<span class="lb-pixel-border" style="display:inline-block;margin:0 0 4px;padding:2px 12px;font-size:.75rem;line-height:1.6;font-weight:500;color:var(--lb-text)">${esc(badge)}</span>` : ""}
          ${displayNameHtml(displayName, theme)}
        </div>
      </div>
      ${bio}
    </header>`;
  }

  // Banner layout: wide image above the classic block.
  const bannerBlock =
    layout === "banner" && banner
      ? `<div style="margin:0 -1rem 1.5rem;width:100%;overflow:hidden;border-radius:var(--lb-card-radius)">
          <img src="${esc(banner)}" alt="" class="lb-export-banner-sm" style="${adjustmentStyleString({ fit: page.bannerFit, posX: page.bannerPosX, posY: page.bannerPosY, zoom: page.bannerZoom })}" />
        </div>`
      : "";

  // Classic (default).
  return `<header style="display:flex;flex-direction:column;align-items:center;text-align:center;color:var(--lb-text)">
    ${bannerBlock}
    ${avatarHtml(page, theme)}
    ${badgeHtml}
    <div style="${nameReveal}">${displayNameHtml(displayName, theme)}</div>
    ${bio}
  </header>`;
}

// ─── Socials ────────────────────────────────────────────────────────────────

function socialsHtml(socialLinks: SocialLink[], theme: ThemeInput): string {
  if (socialLinks.length === 0) return "";
  const isPixel = theme.linkStyle === "pixel";

  const items = socialLinks
    .map((item) => {
      const platform = (item.platform as SocialPlatform) || "email";
      const href = normalizeSocialUrl(platform, item.url || "");
      if (!href) return "";
      const svg = getSocialIconSvg(platform);
      const label = getPlatformLabel(platform);
      const safeHref = href.replace(/"/g, "&quot;");

      if (isPixel) {
        const clipOuter =
          "polygon(6px 0,calc(100% - 6px) 0,calc(100% - 6px) 3px,calc(100% - 3px) 3px,calc(100% - 3px) 6px,100% 6px,100% calc(100% - 6px),calc(100% - 3px) calc(100% - 6px),calc(100% - 3px) calc(100% - 3px),calc(100% - 6px) calc(100% - 3px),calc(100% - 6px) 100%,6px 100%,6px calc(100% - 3px),3px calc(100% - 3px),3px calc(100% - 6px),0 calc(100% - 6px),0 6px,3px 6px,3px 3px)";
        const clipInner =
          "polygon(4px 0,calc(100% - 4px) 0,calc(100% - 4px) 2px,calc(100% - 2px) 2px,calc(100% - 2px) 4px,100% 4px,100% calc(100% - 4px),calc(100% - 2px) calc(100% - 4px),calc(100% - 2px) calc(100% - 2px),calc(100% - 4px) calc(100% - 2px),calc(100% - 4px) 100%,4px 100%,4px calc(100% - 2px),2px calc(100% - 2px),2px 4px,0 4px)";
        return `<div class="lb-pixel-social" style="position:relative;width:42px;height:42px">
          <div style="position:absolute;inset:0;background:var(--lb-accent);clip-path:${clipOuter}"></div>
          <a href="${safeHref}" target="_blank" rel="noopener noreferrer" aria-label="${esc(label)}" class="lb-social-icon" style="position:absolute;inset:3px;display:inline-flex;align-items:center;justify-content:center;background:var(--lb-card-bg);color:var(--lb-text);clip-path:${clipInner}">${svg}</a>
        </div>`;
      }

      return `<a href="${safeHref}" target="_blank" rel="noopener noreferrer" aria-label="${esc(label)}" class="lb-social-icon" style="display:inline-flex;align-items:center;justify-content:center;width:42px;height:42px;border-radius:var(--lb-card-radius);background:var(--lb-card-bg);color:var(--lb-text);border:var(--lb-border-width) solid var(--lb-card-border);transition:transform .15s ease,border-color .15s ease;backdrop-filter:blur(var(--lb-blur));-webkit-backdrop-filter:blur(var(--lb-blur))">${svg}</a>`;
    })
    .filter(Boolean)
    .map((html) => `<span>${html}</span>`)
    .join("\n");

  if (!items) return "";
  return `<nav aria-label="Social links" style="display:flex;flex-wrap:wrap;align-items:center;justify-content:center;gap:12px;margin:24px 0 32px">${items}</nav>`;
}

// ─── Section header ─────────────────────────────────────────────────────────

function sectionHeaderHtml(
  section: SectionLike,
  delayMs: number,
  theme: ThemeInput,
): string {
  const raw = section.icon?.trim();
  const animationType =
    theme.animationType === "none" ? "none" : theme.animationType || "lift";
  const reveal = revealAnimation(animationType, delayMs);
  const centered = (theme.alignment || "center") === "center";

  const ruleStyle =
    "flex:1;height:1px;min-width:24px;background:linear-gradient(to right, var(--lb-accent) 0%, color-mix(in srgb, var(--lb-accent) 22%, transparent) 45%, transparent 100%);opacity:.55";
  const ruleStartStyle =
    "flex:1;height:1px;min-width:24px;background:linear-gradient(to left, var(--lb-accent) 0%, color-mix(in srgb, var(--lb-accent) 22%, transparent) 45%, transparent 100%);opacity:.55";

  let iconHtml = "";
  if (raw) {
    if (isLucideIconName(raw)) {
      const svg = lucideIconSvgString(raw, 15);
      iconHtml = svg
        ? `<span class="lb-section-icon" style="display:inline-flex;color:var(--lb-text);flex-shrink:0">${svg}</span>`
        : "";
    } else {
      iconHtml = `<span aria-hidden="true" style="font-size:15px;line-height:1">${esc(raw)}</span>`;
    }
  }

  return `<div class="lb-section-header" style="display:flex;align-items:center;justify-content:${centered ? "center" : "flex-start"};gap:10px;width:100%;margin-bottom:calc(var(--lb-spacing) * 1.5);${reveal}">
    ${centered ? `<div aria-hidden="true" style="${ruleStartStyle}"></div>` : ""}
    ${iconHtml}
    <h2 style="margin:0;font-size:max(calc(var(--lb-font-size) * 0.72), 11px);font-weight:600;text-transform:uppercase;letter-spacing:.14em;font-family:var(--lb-font);color:var(--lb-text);opacity:.85;white-space:nowrap;flex-shrink:0">${esc(section.title)}</h2>
    <div aria-hidden="true" style="${ruleStyle}"></div>
  </div>`;
}

