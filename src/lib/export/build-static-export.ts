/**
 * lucide icon → inline SVG string. Same render contract as
 * build-link-card.ts's private helper (props.iconNode ≤1.44 /
 * props.icon.node ≥1.45); duplicated here so the shared builder file
 * stays untouched (#80 two-worktree rule).
 */
const LUCIDE_SVG_ATTRS =
  'xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';

function svgAttrs(attrs: Record<string, string>): string {
  return Object.entries(attrs)
    .filter(([k]) => k !== "key")
    .map(([k, v]) => `${k}="${esc(String(v))}"`)
    .join(" ");
}

export function lucideIconSvgString(name: string, size = 20): string | null {
  const Component = resolveIcon(name);
  if (!Component) return null;
  type RenderedIcon = {
    props: {
      iconNode?: Array<[string, Record<string, string>]>;
      icon?: { node?: Array<[string, Record<string, string>]> };
    };
  };
  const el = (
    Component as unknown as {
      render: (p: Record<string, unknown>, ref: null) => RenderedIcon;
    }
  ).render({ size }, null);
  const node = el.props.iconNode ?? el.props.icon?.node;
  if (!node) return null;
  const inner = node
    .map(([tag, attrs]) => `<${tag} ${svgAttrs(attrs)}></${tag}>`)
    .join("");
  return `<svg ${LUCIDE_SVG_ATTRS} width="${size}" height="${size}" aria-hidden="true">${inner}</svg>`;
}

