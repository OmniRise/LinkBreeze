/**
 * Static-export probe (#80, backlog item 2.2) — run with:
 *   npx tsx scripts/probe-static-export.ts
 * Writes /tmp/sample-export.html from a fixture dataset and asserts the
 * document structure end to end (no vitest, no next build). Throwaway
 * verification harness; not imported by app code.
 */
import { writeFileSync } from "node:fs";
import {
  buildStaticExport,
  type ExportInput,
} from "../src/lib/export/build-static-export";
import { assertExportSize } from "../src/lib/export/size";
import type { LinkRow } from "../src/server/queries";

const makeLink = (over: Record<string, unknown>): LinkRow =>
  ({
    id: 1,
    pageId: 1,
    sectionId: null,
    orderIndex: 0,
    type: "url",
    title: "My Site",
    description: null,
    url: "https://example.com",
    icon: null,
    iconUrl: null,
    customIconUrl: null,
    iconMode: "auto",
    autoIcon: true,
    imageUrl: null,
    isHighlighted: false,
    isActive: true,
    scheduleStart: null,
    scheduleEnd: null,
    clicksCount: 0,
    cardStyle: "compact",
    popupText: null,
    ctaLabel: null,
    redirectSlug: null,
    createdAt: "2026-01-01 00:00:00",
    ...over,
  }) as unknown as LinkRow;

const input: ExportInput = {
  page: {
    slug: "@janedoe",
    title: "Jane Doe",
    bio: "Designer & maker of things",
    seoTitle: "Jane Doe - links",
    seoDescription: "All my links in one place",
    badgeText: "Pro",
    socialLinks: JSON.stringify([
      { platform: "github", url: "https://github.com/jane" },
      { platform: "youtube", url: "https://youtube.com/@jane" },
    ]),
    avatarUrl: "/api/uploads/avatar-probe.png",
    bannerUrl: null,
    footerText: "© 2026 Jane Doe",
    customCss: ".probe { outline: none; }",
    analyticsScript:
      '<script async src="https://plausible.io/js/script.js" data-domain="jane.dev"></script>',
  },
  links: [
    makeLink({
      id: 1,
      title: "Portfolio",
      description: "My design work",
      url: "https://janedoe.design",
      redirectSlug: "portfolio",
      isHighlighted: true,
      iconUrl: "/api/uploads/favicon-abc.png",
    }),
    makeLink({ id: 2, sectionId: 7, title: "Blog", url: "https://blog.janedoe.dev" }),
    makeLink({ id: 3, type: "divider", title: "Break", sectionId: 7 }),
    makeLink({
      id: 4,
      type: "text",
      title: "About me",
      popupText: "Hello **world** — I make things.",
      ctaLabel: "Read more",
      url: "https://janedoe.design/about",
    }),
    makeLink({
      id: 5,
      type: "embed",
      title: "Latest video",
      url: "https://www.youtube.com/watch?v=dQw4w9WgXcQ",
    }),
    makeLink({ id: 6, title: "Email me", url: "mailto:jane@example.com" }),
  ],
  sections: [{ id: 7, title: "Writing", icon: "📝", orderIndex: 0 }],
  theme: {
    primaryColor: "#533fd6",
    secondaryColor: "#a78bfa",
    textColor: "#eceafe",
    linkStyle: "glass",
    animationType: "lift",
    backgroundType: "gradient",
    backgroundValue: "#0a0820,#1a1040",
    fontScale: "110",
    density: "normal",
  },
  baseUrl: "https://links.example.com",
};

const html = buildStaticExport(input);
writeFileSync("/tmp/sample-export.html", html);

// ── Structural assertions (fail loudly) ─────────────────────────────────────
const checks: Array<[string, boolean]> = [
  ["doctype", html.startsWith("<!DOCTYPE html>")],
  ["generator tag", html.includes("Generated by LinkBreeze")],
  ["theme tokens", html.includes("--lb-accent: #533fd6;")],
  ["direct href (redirectSlug)", html.includes('href="https://janedoe.design"')],
  ["no /go/ refs", !html.includes("/go/")],
  ["no beacons", !html.includes("sendBeacon")],
  ["mailto preserved", html.includes('href="mailto:jane@example.com"')],
  ["absolutized avatar", html.includes('src="https://links.example.com/api/uploads/avatar-probe.png"')],
  ["popup dialog", html.includes('<dialog id="lb-popup-4"')],
  ["embed fallback link", html.includes('href="https://www.youtube.com/watch?v=dQw4w9WgXcQ"') && !html.includes("<iframe")],
  ["divider", html.includes('role="separator"')],
  ["section header", html.includes("Writing")],
  ["socials", html.includes('aria-label="GitHub"')],
  ["analytics kept", html.includes("plausible.io")],
  ["custom css kept", html.includes(".probe { outline: none; }")],
  ["footer", html.includes("© 2026 Jane Doe")],
  ["json-ld", html.includes('application/ld+json')],
  ["size ok", assertExportSize(html).ok],
];
let failed = 0;
for (const [name, ok] of checks) {
  console.log(`${ok ? "PASS" : "FAIL"}  ${name}`);
  if (!ok) failed++;
}
console.log(`\nbytes: ${Buffer.byteLength(html, "utf-8")}`);
console.log("wrote /tmp/sample-export.html");
if (failed > 0) {
  console.error(`${failed} check(s) failed`);
  process.exit(1);
}
